// Bundle the platform into one self-contained HTML file for artifact preview.
// This is the REVIEW path: Austin clicks through a build with no backend and no
// deploy, so nothing reaches the live site or the live database until he says so.
//   node platform/tools/build-artifact.mjs [seedPath] [outPath]
// No bundler dependency: modules are concatenated in dependency order with
// import/export lines stripped (names are unique across modules by convention).
// Usage: node platform/tools/build-artifact.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = p => readFileSync(resolve(root, p), 'utf8');
const SEED_PATH = process.argv[2] || 'data/slice-f1.json';
const OUT_PATH = process.argv[3] || 'dist/h2sep-slice.html';

const ORDER = [
  'js/config.js',
  'js/core/ui.js',
  'js/core/store.js',
  'js/core/registry.js',
  'js/modules/tracking/module.js',
  'js/modules/directory/module.js',
  'js/modules/bim/module.js',
  'js/app.js',
];

function stripModuleSyntax(src) {
  return src
    .replace(/^import\s[^;]*;\s*$/gm, '')
    .replace(/^export\s+(async\s+)?function/gm, '$1function')
    .replace(/^export\s+class/gm, 'class')
    .replace(/^export\s+const/gm, 'const')
    .replace(/^export\s*\{[^}]*\};\s*$/gm, '');
}

const css = read('css/app.css');
const seed = read(SEED_PATH);
const logoB64 = readFileSync(resolve(root, 'img/triun-logo.png')).toString('base64');
const viewer = read('room3d.html');

// Floor 1 assembled: platform/floor3d.html is GENERATED by build_floor3d.mjs
// with three.js inlined, so it is already self-contained except for one fetch,
// data/floor1-staged.json, its live status paint. A srcdoc frame has no URL to
// fetch relative to, so the bundle carries both: the page as
// window.__H2SEP_FLOOR_SRCDOC and the checklist state as window.__H2SEP_FLOOR_DATA.
// The scene's loadData() takes the injected object before it fetches, and the
// BIM module hands it into the frame ahead of the page's first script.
// Every check below is a hard failure on purpose: a bundle that quietly shipped
// without the floor scene would show the module's hard stop, which is honest,
// but a bundle that shipped a scene missing its hook would frame a page that
// tries to fetch and then says its paint is unavailable. Better to stop here.
const floor = read('floor3d.html');
const floorDataText = read('data/floor1-staged.json');
if (!/GENERATED FILE - do not hand edit/.test(floor)) {
  throw new Error('build-artifact: platform/floor3d.html is not the generated page; run node platform/tools/build_floor3d.mjs first');
}
if (floor.indexOf('__H2SEP_FLOOR_DATA') === -1) {
  throw new Error('build-artifact: platform/floor3d.html has no window.__H2SEP_FLOOR_DATA hook, so inlined status data could not reach it');
}
if (floor.indexOf('<script>') === -1) {
  throw new Error('build-artifact: platform/floor3d.html has no <script> tag for the BIM module to inject the status data ahead of');
}
if (/<script[^>]+src=/.test(floor)) {
  throw new Error('build-artifact: platform/floor3d.html still loads an external script; the packaged frame cannot fetch it');
}
const floorData = JSON.parse(floorDataText);   // throws on a malformed checklist file
const floorDocCount = Object.keys(floorData.docs || {}).length;
if (!floorDocCount) throw new Error('build-artifact: data/floor1-staged.json carries no docs');
// Re-serialized compact: the file on disk is pretty-printed for diffs and the
// bundle does not need the whitespace.
const floorDataCompact = JSON.stringify(floorData);

// Module scope is strict: two top-level declarations of one name across the
// concatenated files is a SyntaxError that blanks the whole page before any
// screen renders. Names are meant to be unique by convention, so enforce it
// here. A byte-identical one-line helper declared twice (nowIso in store.js and
// directory/module.js) is dropped from the later module; anything else stops
// the build with the two files named.
const DECL = /^(?:async\s+)?(?:function\s*\*?\s*|class\s+|const\s+|let\s+|var\s+)([A-Za-z_$][\w$]*)/;
const seen = new Map();   // name -> { file, line }
function dedupe(file, src) {
  const out = [];
  for (const line of src.split('\n')) {
    const m = DECL.exec(line);
    if (!m) { out.push(line); continue; }
    const name = m[1];
    const prior = seen.get(name);
    if (!prior) { seen.set(name, { file, line }); out.push(line); continue; }
    const oneLiner = /^function\s/.test(line) && /\}\s*$/.test(line);
    if (oneLiner && prior.line === line) {
      out.push(`/* ${name}: identical to the copy in ${prior.file}, dropped by the bundler */`);
      continue;
    }
    throw new Error(`build-artifact: top-level name "${name}" is declared in both ${prior.file} and ${file}; rename one, the bundle would not parse`);
  }
  return out.join('\n');
}

const js = ORDER.map(p => `/* ---- ${p} ---- */\n` + dedupe(p, stripModuleSyntax(read(p)))).join('\n');
const guard = s => s.replace(/<\/script/gi, '<\\/script');

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8"/>
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover"/>
<meta name="color-scheme" content="light dark"/>
<title>H2SEP Platform Slice</title>
<style>${css}</style>
</head>
<body>
<div id="app" aria-live="polite"></div>
<script>
window.__H2SEP_NO_BACKEND = 1; // artifact pages cannot reach external hosts; local mode
window.__H2SEP_SEED = ${guard(seed)};
window.__H2SEP_LOGO = "data:image/png;base64,${logoB64}";
window.__H2SEP_VIEWER_SRCDOC = ${guard(JSON.stringify(viewer))};
window.__H2SEP_FLOOR_SRCDOC = ${guard(JSON.stringify(floor))};
window.__H2SEP_FLOOR_DATA = ${guard(floorDataCompact)}; // ${floorDocCount} checklist documents, inlined at build time
window.__H2SEP_FLOOR_DATA_NOTE = ${JSON.stringify(`${floorDocCount} checklist documents from data/floor1-staged.json, inlined when this bundle was built`)};
</script>
<script type="module">
${guard(js)}
</script>
</body>
</html>`;

mkdirSync(dirname(resolve(root, OUT_PATH)), { recursive: true });
writeFileSync(resolve(root, OUT_PATH), html);
console.log(`wrote platform/${OUT_PATH} from ${SEED_PATH}`, html.length, 'bytes',
  `(floor3d.html ${floor.length} bytes + ${floorDocCount} floor checklist docs inlined)`);
